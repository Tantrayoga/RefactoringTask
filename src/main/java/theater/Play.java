package theater;

/**
 * Represents a theatrical play with a name and a type/genre.
 * This class is part of the 'theater' package.
 */
public class Play {

    private String name;
    private String type;

    public Play(String name, String type) {
        this.name = name;
        this.type = type;
    }

    public String getName() {
        return this.name;
    }

    public String getType() {
        return this.type;
    }
}
